/* Импорт вопросов из .docx-пачек: достаёт только сам вопрос и варианты ответов.
   Коэффициенты, правила расчёта и справочные блоки отбрасываются — на сайте
   хранится вопрос + options, остальным полям в events.json места нет. */

const DOCX_DIR = __DIR__ . '/../data/docx';

/* Служебные строки таблицы и хвост карточки вопроса. Всё, что начинается с
   этих префиксов, к вариантам ответа не относится. */
const DOCX_SKIP_PREFIXES = [
    'Засчитывается:', 'Не засчитывается:', 'Если ситуация спорная:',
    'Если данных нет вовремя:', 'Источник:', 'Контекст:', 'ИИ анализ:',
    'Обновление:', 'Примечание:',
    // Правило ничьей в таблицах сравнения активов — не вариант ответа.
    'При равенстве',
];

/* Достаёт word/document.xml из .docx без расширения zip: читает центральный
   каталог архива и разжимает одну запись через gzinflate (метод deflate) или
   берёт как есть (метод store). Расширения zip в контейнере нет, а тянуть его
   ради одного файла на пачку не стоит. */
function docx_read_document_xml(string $path): ?string {
    $data = @file_get_contents($path);
    if ($data === false) return null;

    // Ищем локальный заголовок записи word/document.xml (сигнатура PK\3\4).
    $name = "word/document.xml";
    $pos  = 0;
    while (($pos = strpos($data, "PK\x03\x04", $pos)) !== false) {
        $method   = unpack('v', substr($data, $pos + 8, 2))[1];
        $compSize = unpack('V', substr($data, $pos + 18, 4))[1];
        $nameLen  = unpack('v', substr($data, $pos + 26, 2))[1];
        $extraLen = unpack('v', substr($data, $pos + 28, 2))[1];
        $entry    = substr($data, $pos + 30, $nameLen);
        $start    = $pos + 30 + $nameLen + $extraLen;

        if ($entry === $name && $compSize > 0) {
            $raw = substr($data, $start, $compSize);
            $out = $method === 8 ? @gzinflate($raw) : $raw;
            if ($out !== false && $out !== '') return $out;
        }
        $pos = $start + max($compSize, 1);
    }
    return null;
}

function docx_paragraphs(string $path): array {
    $xml = docx_read_document_xml($path);
    if ($xml === null) return [];

    // </w:p> — граница абзаца; теги вырезаем, сущности разворачиваем.
    $xml = preg_replace('~</w:p>~u', "\n", $xml);
    $txt = strip_tags($xml);
    $txt = html_entity_decode($txt, ENT_QUOTES | ENT_XML1, 'UTF-8');

    $out = [];
    foreach (explode("\n", $txt) as $line) {
        $line = trim(preg_replace('~\s+~u', ' ', $line));
        if ($line !== '') $out[] = $line;
    }
    return $out;
}

function docx_is_meta(string $line): bool {
    foreach (DOCX_SKIP_PREFIXES as $p) {
        if (mb_strpos($line, $p) === 0) return true;
    }
    return false;
}

/* Ячейка коэффициента: «10.00 (10%)», «1.11 (90%)». Такие строки идут следом
   за вариантом и в ответ не попадают. */
function docx_is_odds(string $line): bool {
    return (bool) preg_match('~^\d+[.,]\d+\s*\(\d+%\)$~u', $line);
}

/* Служебные ячейки таблиц сравнения активов. У таких вопросов колонки
   «Актив | Движение | ДА | НЕТ», а строки несут проценты роста и цены в центах:
       BTC | ▲ +52.7% | 56¢ | 44¢
   Вариантом ответа является только первая колонка; всё остальное — числа,
   которые попадали в список ответов и превращались в бессмысленные сюжеты. */
function docx_is_table_noise(string $line): bool {
    // Заголовки колонок.
    if (in_array($line, ['Актив', 'Движение', 'Вариант', 'ДА', 'НЕТ'], true)) return true;
    // Проценты со стрелкой: «▲ +52.7%», «▼ -3,1 %».
    if (preg_match('~^[▲▼△▽↑↓]\s*[+\-−]?\s*\d+[.,]?\d*\s*%$~u', $line)) return true;
    // Цена в центах: «56¢».
    if (preg_match('~^\d+\s*¢$~u', $line)) return true;
    // Голый процент или число: «+17.4%», «52,7 %».
    if (preg_match('~^[+\-−]?\d+[.,]?\d*\s*%$~u', $line)) return true;
    return false;
}

function docx_is_question(string $line): bool {
    return (bool) preg_match('~^\d+\.\s+\S~u', $line) && mb_strpos($line, '?') !== false;
}

/** Разбирает один файл в список ['question' => ..., 'options' => [...]]. */
function docx_parse(string $path): array {
    $lines = docx_paragraphs($path);
    $questions = [];
    $current = null;

    foreach ($lines as $line) {
        if (docx_is_question($line)) {
            if ($current && $current['options']) $questions[] = $current;
            $current = [
                'question' => trim(preg_replace('~^\d+\.\s*~u', '', $line)),
                'options'  => [],
            ];
            continue;
        }
        if (!$current) continue;                    // шапка файла до первого вопроса
        if (docx_is_meta($line)) continue;          // правила расчёта и справка
        if (docx_is_odds($line)) continue;          // коэффициенты
        if (docx_is_table_noise($line)) continue;   // шапки колонок, проценты роста, центы

        // Осталась строка варианта. Дубли внутри одного вопроса отсекаем.
        if (!in_array($line, $current['options'], true)) {
            $current['options'][] = $line;
        }
    }
    if ($current && $current['options']) $questions[] = $current;

    // Вопрос без вариантов (только ДА/НЕТ в шапке) — бинарный.
    foreach ($questions as &$q) {
        if (!$q['options']) $q['options'] = ['Да', 'Нет'];
    }
    return $questions;
}

/* Сюжеты для картинок: короткие английские описания, которые потом рисует
   img_prewarm. Одно на событие + по одному на вариант — так вариантные
   миниатюры отличаются друг от друга, а не повторяют общую картинку.
   Возвращает ['event'=>string, 'options'=>[i=>string]] либо [] при неудаче —
   импорт в этом случае просто идёт без картинок, а не падает. */
function docx_art_prompts(string $question, array $options): array {
    if (!function_exists('gemini_fallback')) {
        // news.php несёт собственный роутер и на подключении сам ответил бы на
        // запрос («unknown action»). NEWS_INCLUDE переводит его в режим библиотеки.
        if (!defined('NEWS_INCLUDE')) define('NEWS_INCLUDE', true);
        // Его верхний уровень объявляет $CONFIG/$NEWS как ГЛОБАЛЬНЫЕ, а cfg()
        // читает их через global. Подключение изнутри функции положило бы их в
        // локальную область — cfg() увидела бы пустоту и отчиталась «нет ключей».
        require_once __DIR__ . '/news.php';
        foreach (['CONFIG', 'NEWS', 'DATA'] as $v) {
            if (isset(${$v})) $GLOBALS[$v] = ${$v};
        }
    }
    if (!function_exists('gemini_fallback')) return [];

    $list = '';
    foreach ($options as $i => $o) $list .= ($i + 1) . '. ' . $o . "\n";

    $prompt = <<<TXT
Ты подбираешь сюжеты для новостных фотографий к вопросу прогнозного рынка.

ВОПРОС: {$question}
ВАРИАНТЫ:
{$list}
Верни СТРОГО JSON без пояснений:
{"event":"...","options":["...","..."]}

Правила:
- "event" — сюжет фотографии к самому вопросу.
- "options" — по одному сюжету на каждый вариант, ровно в том же порядке и количестве.
- Каждый сюжет: короткая фраза НА АНГЛИЙСКОМ, 3-8 слов, конкретный видимый объект или сцена.
- Никаких дат, цифр, процентов, надписей и текста на изображении.
ВАРИАНТЫ ОТВЕТА БЫВАЮТ ЧЕТЫРЁХ ВИДОВ. Для каждого — своё правило:

1) ПРЕДМЕТНЫЙ вариант — страна, регион, компания, актив, человек, исход
   («Белгородская область», «Швеция», «Binance», «Золото», «Перемирие», «Россия»).
   Это самый ценный случай: рисуй ИМЕННО ЭТОТ предмет, чтобы варианты отличались
   с одного взгляда. Область и страну показывай узнаваемой сценой на месте
   («Russian soldiers at a Belgorod checkpoint»), актив — самим предметом
   (слиток золота, нефтяная качалка, пачка банкнот), компанию — вывеской.
   Варианты одного вопроса должны быть РАЗНЫМИ картинками, а не одной и той же.

2) ВАРИАНТ-СРОК — «В августе», «В октябре», «В ноябре-декабре», «До конца сентября».
   Само по себе время нарисовать нельзя. Рисуй СОБЫТИЕ ИЗ ВОПРОСА, меняя ракурс или
   деталь сцены: подготовка, само действие, последствия.
   ЗАПРЕЩЕНО подменять событие временем года: «жёлтые листья», «снег», «новогодние
   украшения», «календарь», «часы» — это картинка про месяц, а не про ответ.
   Для вопроса о мобилизации: «В октябре» → «Russian conscripts boarding a military
   bus», а НЕ «autumn leaves near a building».

3) ВАРИАНТ-ОТРИЦАНИЕ — «Не введут», «Не подпишут», «Ни то ни другое», «Никто».
   Покажи ОТСУТСТВИЕ события в том же месте: пустая приёмная, закрытые двери,
   безлюдный блокпост, спокойная обычная улица. Место должно быть узнаваемо тем же,
   что и в остальных вариантах, — меняется только то, что ничего не происходит.

4) ВАРИАНТ-ЧИСЛО — «Менее 35%», «От 500 до 1000», «Более 2000», «▲ +58.4%».
   Число рисовать нельзя, надпись выйдет мусором. Показывай МАСШТАБ ЯВЛЕНИЯ:
   «Менее 500 человек» → небольшая группа; «Более 2000» → большая колонна;
   «Менее 35%» → лёгкие повреждения объекта; «Более 55%» → сильные разрушения.
   Для чистых биржевых процентов («▲ +58.4%») бери сам актив или биржевой зал,
   но НЕ стрелку роста — одинаковые стрелки во всех вариантах бесполезны.

СНАЧАЛА РАЗБЕРИ ВОПРОС, ПОТОМ ПОДБИРАЙ СЮЖЕТ:
- Определи, О ЧЁМ именно спрашивают: о встрече, подписании, отставке, выборах, цене,
  захвате города, запуске, приговоре. Сюжет должен показывать ИМЕННО ЭТО ДЕЙСТВИЕ.
- Не подменяй суть общим фоном темы. Примеры подмены, которых быть не должно:
  вопрос про перемирие → «руины города» (это фон войны, а не перемирие);
  вопрос про решение по ставке → «здание банка» (нужно заседание/подписание);
  вопрос про выборы → «флаг страны» (нужны урна, бюллетень, участок).
- Если вопрос — ВЫБОР МЕЖДУ ДВУМЯ СОБЫТИЯМИ («что случится раньше: А или Б»),
  сюжет вопроса должен показывать сам предмет спора или оба исхода рядом,
  а варианты — каждый своё событие по отдельности.
- Называй конкретное место, если оно есть в вопросе (город, страна, здание).
- Сюжет — это ФИЗИЧЕСКОЕ ДЕЙСТВИЕ ИЛИ ПРЕДМЕТ, который видно на фотографии.
  Избегай слов, за которые модель цепляется и рисует переговорную с экраном:
  «announcement», «press conference», «meeting», «decision», «statement», «summit».
  Вместо «mobilization announcement press conference» → «Russian conscripts boarding
  a military bus». Вместо «rate decision meeting» → «Jerome Powell at a microphone».
- ГРАФИКИ, ЭКРАНЫ, МОНИТОРЫ, БИРЖЕВЫЕ ТАБЛО — почти всегда ЗАПРЕЩЕНЫ: модель
  дорисовывает на них бессмысленные латинские надписи, и кадр превращается в
  «человек смотрит в монитор» независимо от темы вопроса.
  Единственное исключение — вопрос ПРЯМО о биржевой цене, курсе, индексе или котировке
  (биткоин, эфириум, акции, нефть, золото, индексы, курс валюты). Там допустим ОДИН
  экран или табло, но и в этом случае лучше показать людей: трейдера в зале, толпу у
  обменника, слиток золота в руках, бочки нефти.
  Во всех прочих вопросах — про политику, войну, выборы, законы, санкции, отставки,
  спорт, происшествия — экранов и графиков быть НЕ ДОЛЖНО вообще.
  Про заправки, магазины, товары рисуй сами колонки, ценники, полки и людей, а не табло.
- ЗАПРЕЩЕНЫ подмены события «указателем на тему». Ни в "event", ни в вариантах не бывает:
  географических карт («map of Russia», «map showing regions»), пустых зданий парламентов
  и ведомств, календарей, часов, флагов на флагштоке, документов с печатью, дорожных
  указателей. Это картинки про тему вообще, а не про то, случилось событие или нет.
  Вопрос «введут ли военное положение в приграничных областях» → НЕ «карта России»,
  а «Russian soldiers at a checkpoint on a city street».
  Вопрос «до какого срока продлят» → НЕ «календарь», а само заседание или голосование.
- Спрашивай себя: если событие ПРОИЗОЙДЁТ, что увидит фотограф на месте? Это и рисуй:
  людей, технику, действие. Место и страну добавляй словом, а не картой.
- Это правило в полной мере относится и к "event": сюжет вопроса — тоже действие,
  а не фасад. «Ukrainian parliament building exterior» — плохо, «deputies voting inside
  the Ukrainian parliament» — правильно. Здание снаружи допустимо, только если вопрос
  буквально о самом здании.
- В кадре почти всегда должны быть ЛЮДИ, занятые этим действием, — кроме вопросов
  о ценах, товарах, технике и природных явлениях.

МЕСТО ДЕЙСТВИЯ:
- Если событие происходит в России (или названы российские органы, компании, города —
  Кремль, ЦБ РФ, Росстат, Мосбиржа, Роскомнадзор, Москва, Петербург) — сюжет должен
  выглядеть российским: советская и российская архитектура, панельные дома, отечественные
  автомобили, зимние городские улицы, обстановка российского учреждения.
- В КАЖДЫЙ такой сюжет обязательно вставляй слово Russian или Moscow — иначе
  рисуется западная сцена по умолчанию. «military enlistment office» — плохо,
  «Russian military enlistment office» — правильно.
- НЕ вставляй в такие сюжеты приметы США и Западной Европы: американские флаги и офисы,
  вывески и указатели на английском, западные торговые сети, небоскрёбы делового центра.
- Не проси изображать на картинке никакие надписи и текст: они выходят бессмысленным
  набором латинских букв. Только предметы, здания, техника, люди, обстановка.
- Для других стран действует то же правило: сцена должна выглядеть как эта страна.

ПРЕДМЕТ ВОПРОСА ДОЛЖЕН БЫТЬ В КАДРЕ:
- Если спрашивают про запрет, ограничение, налог или разрешение ЧЕГО-ТО — в кадре должно
  быть само это «что-то», а не только те, кто принимает решение.
  «Кто запретит майнинг» → НЕ «чиновники обсуждают правила», а «стойки майнинг-ферм с
  видеокартами», можно с инспектором рядом.
  «Запретят ли продажу авто с ДВС» → машины в салоне, а не депутаты в зале.
  «Введут ли налог на криптовалюту» → монеты и кошелёк, а не совещание.
- Совещания, залы заседаний и людей с документами используй ТОЛЬКО когда вопрос
  буквально о голосовании, заседании или подписании. Во всех прочих случаях покажи
  сам предмет: технику, товар, здание, животное, оборудование.

СЛОВА С ДВУМЯ ЗНАЧЕНИЯМИ — бери то, что имеется в виду в вопросе:
- «рынок» в вопросах про доли, объёмы, котировки — это ФИНАНСОВЫЙ рынок, а не базар
  и не лавка с торговцами. Не рисуй прилавки, монеты в руках, продавцов.
- «курс» — обменный курс валюты, а не учебный курс; «ставка» — процентная ставка,
  а не ставка в игре; «бумаги» — ценные бумаги, а не листы; «фронт» — линия боевых
  действий, а не погодный фронт.
- Для абстрактных финансовых понятий (доля рынка, объём торгов, капитализация)
  показывай узнаваемый предмет темы: монеты и банкноты нужной валюты, здание биржи,
  логотип компании, телефон с приложением — но НЕ сцену уличной торговли.

КОМПАНИИ И БРЕНДЫ:
- Если в вопросе названа компания, биржа, банк или сервис (Binance, Coinbase, Газпром,
  Сбербанк, Яндекс, Volkswagen, ВТБ, Лукойл) — она должна быть ГЛАВНЫМ ПРЕДМЕТОМ кадра,
  а её название стоять В НАЧАЛЕ фразы. Модель читает первые слова и рисует именно их;
  название в конце она пропускает.
  «European Union officials issuing fines against Binance» — ПЛОХО: нарисует чиновников
  с бумагами, никакого Binance в кадре не будет.
  «Binance logo on a glass office building» — ПРАВИЛЬНО.
  «Coinbase app open on a smartphone held in hand» — ПРАВИЛЬНО.
- Показывай компанию через её вещи: вывеска, логотип на здании, приложение на экране
  телефона, фирменная символика на стене офиса. Людей добавляй фоном, а не главным.
- Это правило распространяется и на "event": если компания названа в вопросе, сюжет
  вопроса ОБЯЗАН начинаться с её названия. Не «officials inspecting Binance offices»,
  а «Binance office building with officials at the entrance».
- Когда в вопросе ДВЕ компании, а спрашивают, с какой что случится, — покажи обе рядом
  или ту, о которой конкретный вариант.
- Названия брендов писать латиницей как есть: Binance, Coinbase, Gazprom, Sberbank.
  Это единственный случай, когда буквы в кадре допустимы — фирменный знак.

ГЛАВНОЕ — ЛЮДИ:
- Если в вопросе назван конкретный человек (фамилия политика, президента, чиновника,
  предпринимателя) и понятно, кто это — ставь его ПОЛНОЕ ИМЯ ЛАТИНИЦЕЙ в сюжет:
  и в "event", и в КАЖДЫЙ вариант, где этот человек уместен.
- Пиши общеизвестное написание имени: Viktor Orban, Peter Magyar, Donald Trump,
