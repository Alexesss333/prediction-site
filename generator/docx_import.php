/* ---------- своё хранилище ----------
   Импортированные вопросы живут ОТДЕЛЬНО от events.json: на сайт они не идут,
   ставок по ним нет, это просто банк вопросов с картинками. */
const DOCX_STORE = __DIR__ . '/../data/imported.json';

function docx_store_load(): array {
    if (!is_file(DOCX_STORE)) return [];
    $j = json_decode((string)@file_get_contents(DOCX_STORE), true);
    return is_array($j) ? $j : [];
}

function docx_store_save(array $rows): void {
    $dir = dirname(DOCX_STORE);
    if (!is_dir($dir)) @mkdir($dir, 0777, true);
    // Пишем через временный файл: обрыв на середине не оставит битый JSON.
    $tmp = DOCX_STORE . '.tmp';
    file_put_contents($tmp, json_encode($rows, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));
    rename($tmp, DOCX_STORE);
}

/* Рисует картинку по сюжету и возвращает адрес готового webp.
   $force — перерисовать заново: к затравке подмешивается время, поэтому
   провайдер выдаёт другую картинку, а не достаёт прежнюю из кэша. */
function docx_render_image(string $subject, string $seedSrc, int $w, bool $force = false): array {
    require_once __DIR__ . '/imglib.php';

    $cfg = json_decode((string)@file_get_contents(__DIR__ . '/../data/config.json'), true) ?: [];
    $tpl = $cfg['img_prompt'] ?? '{q}';
    $prompt = (strpos($tpl, '{q}') !== false) ? str_replace('{q}', $subject, $tpl) : ($subject . ', ' . $tpl);

    $salt = $force ? ('|' . microtime(true)) : '';
    $seed = img_hashn($seedSrc . $salt) % 100000;
    $key  = substr(md5($prompt . '|' . $w . '|' . $seed), 0, 20);

    $dir = __DIR__ . '/../data/genimg';
    if (!is_dir($dir)) @mkdir($dir, 0777, true);
    $file = $dir . '/w_' . $key . '.webp';
    $url  = 'data/genimg/w_' . $key . '.webp';

    if (!$force && is_file($file) && filesize($file) > 0) return ['ok'=>true, 'url'=>$url, 'cached'=>true];

    $err = ''; $used = '';
    $raw = img_generate_chain($prompt, $w, $seed, $cfg, $err, $used);
    if ($raw === false || !$raw) return ['ok'=>false, 'error'=>($err ?: 'провайдер не отдал картинку')];

    $wp = img_to_webp($raw);
    if ($wp === false) return ['ok'=>false, 'error'=>'не удалось преобразовать в webp'];

    file_put_contents($file, $wp);
    return ['ok'=>true, 'url'=>$url, 'provider'=>$used];
}

/** Список пачек: по файлу на пачку, в порядке СКАЧИВАНИЯ (по времени файла).
    Алфавит здесь не подходит: файлы приходят пачками по смыслу, и порядок
    выгрузки — это и есть порядок, в котором их собирали. */
function docx_batches(): array {
    if (!is_dir(DOCX_DIR)) return [];
    $files = glob(DOCX_DIR . '/*.docx') ?: [];
    usort($files, fn($a, $b) => filemtime($a) <=> filemtime($b));

    $out = [];
    foreach ($files as $f) {
        if (mb_strpos(basename($f), '~$') === 0) continue;   // временный файл Word
        $q = docx_parse($f);
        $out[] = [
            'file'      => basename($f),
            'name'      => preg_replace('~\.docx$~ui', '', basename($f)),
            'questions' => $q,
            'count'     => count($q),
        ];
    }
    return $out;
}
